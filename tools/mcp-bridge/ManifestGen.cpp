// Build-time generator: writes McpManifest.cpp (the server manifest the bridge serves offline).
// It builds the SAME action registry as the app (core + engine + app actions) and asks a real
// McpSession for its initialize result and tool list, so the bridge can never drift from the app.
//   usage: mcpdaw_manifest <output.cpp>
#include "core/Actions.h"
#include "engine/OfflineRenderer.h"
#include "mcp/McpSession.h"
#include <juce_events/juce_events.h>
#include <iostream>

int main (int argc, char* argv[])
{
    if (argc < 2) { std::cerr << "usage: mcpdaw_manifest <output.cpp>\n"; return 2; }
    juce::ScopedJuceInitialiser_GUI juceInit;
    using namespace mcpdaw;

    ProjectController controller;
    ActionRegistry registry;
    registerCoreActions (registry);
    registerEngineActions (registry);
    registerAppActions (registry, nullptr);
    McpSession session (registry, controller);

    auto init = session.handle (juce::JSON::parse (R"({"jsonrpc":"2.0","id":1,"method":"initialize","params":{}})"))["result"];
    init.getDynamicObject()->removeProperty ("protocolVersion");   // negotiated per client by the bridge
    init.getDynamicObject()->removeProperty ("_meta");             // app-only (seat mode)
    juce::Array<juce::var> versions;
    for (const auto& v : McpSession::supportedProtocolVersions()) versions.add (v);
    const auto tools = session.handle (juce::JSON::parse (R"({"jsonrpc":"2.0","id":2,"method":"tools/list"})"))["result"];

    auto* manifest = new juce::DynamicObject();
    manifest->setProperty ("initialize", init);
    manifest->setProperty ("protocolVersions", versions);
    manifest->setProperty ("tools", tools);
    const auto json = juce::JSON::toString (juce::var (manifest), true);

    // Emit as a byte array: no string-literal length limits (MSVC caps literals at ~16 KB).
    juce::String out;
    out << "// Generated by mcpdaw_manifest from the app's action registry - do not edit.\n"
           "#include \"mcp/McpManifest.h\"\n\nnamespace mcpdaw::mcp\n{\nnamespace\n{\nconst unsigned char kManifest[] = {";
    const auto utf8 = json.toUTF8();
    const auto numBytes = json.getNumBytesAsUTF8();
    for (size_t i = 0; i < numBytes; ++i)
    {
        if (i % 24 == 0) out << "\n    ";
        out << static_cast<int> (static_cast<unsigned char> (utf8[static_cast<int> (i)])) << ",";
    }
    out << "\n    0 };\n}\n\njuce::String manifestJson()\n{\n"
           "    return juce::String::fromUTF8 (reinterpret_cast<const char*> (kManifest), static_cast<int> (sizeof (kManifest) - 1));\n"
           "}\n} // namespace mcpdaw::mcp\n";

    juce::File target (juce::File::getCurrentWorkingDirectory().getChildFile (juce::String::fromUTF8 (argv[1])));
    if (target.existsAsFile() && target.loadFileAsString() == out) return 0;   // unchanged: keep timestamps
    target.getParentDirectory().createDirectory();
    if (! target.replaceWithText (out, false, false, "\n")) { std::cerr << "cannot write " << argv[1] << "\n"; return 1; }
    std::cout << "mcpdaw_manifest: " << registry.all().size() << " tools -> " << argv[1] << "\n";
    return 0;
}
